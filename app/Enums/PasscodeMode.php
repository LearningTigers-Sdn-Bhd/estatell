<?php

namespace App\Enums;

enum PasscodeMode: string
{
    case Generated = 'generated';
    case Custom = 'custom';

    public function label(): string
    {
        return match ($this) {
            self::Generated => __('Generated by TTLock'),
            self::Custom => __('Chosen by estatell'),
        };
    }

    public function description(): string
    {
        return match ($this) {
            self::Generated => __('Works without a gateway. The lock makes the PIN.'),
            self::Custom => __('A random PIN we choose. Needs a gateway at the lock, otherwise a generated PIN is used.'),
        };
    }

    /**
     * @return list<array{value: string, label: string}>
     */
    public static function options(): array
    {
        return array_map(fn (self $mode): array => ['value' => $mode->value, 'label' => $mode->label()], self::cases());
    }
}
